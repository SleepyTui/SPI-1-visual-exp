import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DIRECTIONS,SAMPLES,FAMILY_NAMES,SLOTS,signSVG,iconSVG,streetSVG,lettering} from './sample-art.mjs';
const root=path.dirname(fileURLToPath(import.meta.url));
const write=(name,body)=>{const p=path.join(root,name);fs.mkdirSync(path.dirname(p),{recursive:true});fs.writeFileSync(p,body);};
const manifest={stage:'style-samples',version:1,detailedFamilies:4,compositionDraftFamilies:12,counts:{signs:0,icons:0,streets:0},files:[],fonts:'font-sources/SOURCES.json'};
const assets={directions:DIRECTIONS,samples:SAMPLES,families:FAMILY_NAMES,slots:SLOTS,signs:{},icons:{},streets:{}};
for(let d=0;d<3;d++){
 const dir=DIRECTIONS[d].id;
 for(const s of SAMPLES){
  const icon=iconSVG(s,d),iconPath=`assets/${dir}/icons/${s.id}.svg`;
  assets.icons[`${dir}/${s.id}`]={svg:icon,path:iconPath};write(iconPath,icon);
  manifest.files.push({kind:'icon',direction:dir,scale:s.id,path:iconPath});manifest.counts.icons++;
  for(const depth of ['2d','2.5d'])for(const light of ['lightbox','neon']){
   const svg=signSVG(d,s,depth,light),p=`assets/${dir}/${depth}/${light}/${s.id}.svg`;
   assets.signs[`${dir}/${depth}/${light}/${s.id}`]={svg,path:p};write(p,svg);
   manifest.files.push({kind:'sign',direction:dir,scale:s.id,depth,light,path:p});manifest.counts.signs++;
  }
 }
 for(const depth of ['2d','2.5d'])for(const light of ['lightbox','neon']){
  const svg=streetSVG(d,depth,light),p=`assets/${dir}/streets/${depth}-${light}.svg`;
  assets.streets[`${dir}/${depth}/${light}`]={svg,path:p};write(p,svg);
  manifest.files.push({kind:'street',direction:dir,depth,light,path:p});manifest.counts.streets++;
 }
}
write('manifest.json',JSON.stringify(manifest,null,2));
write('sample-data.js',`/* Generated by generate.mjs. Offline SVG markup and catalogue. */\nglobalThis.STREET_SAMPLES=${JSON.stringify(assets)};\n`);
let sheet='<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="1530" viewBox="0 0 1200 1530"><title>Scale Street: four scales, three art directions. 2.5D lightbox comparison.</title><rect width="1200" height="1530" fill="#111c24"/>';
sheet+=lettering('SCALE STREET / THREE NIGHTS',40,48,26,'space','#f7e2b0','','start');
sheet+=lettering('FOUR SCALES  /  2.5D LIGHTBOX STUDIES',40,72,11,'space','#a6b6b7','','start');
for(let d=0;d<3;d++)sheet+=lettering(`0${d+1} / ${DIRECTIONS[d].en}`,200+d*400,113,13,'space',DIRECTIONS[d].palette[0]);
for(let row=0;row<4;row++){
 sheet+=`<path d="M30 ${125+row*330}H1170" stroke="#344650" stroke-width="1"/>`;
 sheet+=lettering(SAMPLES[row].label,40,145+row*330,10,'space','#a6b6b7','','start');
 for(let d=0;d<3;d++)sheet+=`<g transform="translate(${40+d*400} ${142+row*330})">${assets.signs[`${DIRECTIONS[d].id}/2.5d/lightbox/${SAMPLES[row].id}`].svg.replace(/^<svg[^>]*>/,'').replace(/<\/svg>$/,'')}</g>`;
}
sheet+=lettering('ORIGINAL VECTOR STUDIES / 48 SIGNS + 12 ICONS + 12 STREETS',40,1505,11,'space','#a6b6b7','','start')+'</svg>';
write('overview.svg',sheet);
console.log(`Generated ${manifest.counts.signs} sign SVGs, ${manifest.counts.icons} icons, ${manifest.counts.streets} street SVGs.`);
